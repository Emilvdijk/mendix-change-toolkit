import fs from 'node:fs';
const MARK_A = '<!-- SECTION INDEX: generated by tools/section-index.mjs, do not edit by hand -->';
const MARK_B = '<!-- END SECTION INDEX -->';

for (const f of process.argv.slice(2)) {
  let text = fs.readFileSync(f, 'utf8');
  // Drop any previous index so the line numbers below are the real ones.
  const a = text.indexOf(MARK_A);
  if (a !== -1) {
    const b = text.indexOf(MARK_B);
    text = text.slice(0, a) + text.slice(b + MARK_B.length).replace(/^\n+/, '');
  }
  const lines = text.split('\n');

  // Where to put it: after the opening blockquote block, before the first `## `.
  let at = lines.findIndex(l => /^## /.test(l));
  if (at < 0) { console.log(`${f}: no sections`); continue; }
  while (at > 0 && lines[at - 1].trim() === '') at--;
  if (lines[at - 1] === '---') at--;

  // The index shifts every line below it, so count its own height first.
  const heads = [];
  lines.forEach((l, i) => { if (/^## /.test(l)) heads.push({ i, t: l.replace(/^##\s*/, '') }); });
  const body = heads.map(h => `${h.t}  §L${h.i + 1}`);
  const block = [MARK_A, '',
    '> **Read a section, not the file.** This document is '
      + `${(fs.statSync(f).size / 1024).toFixed(0)} KB and re-read on every model call `
      + 'that follows it — measured at 1.4M cache-read tokens in one build session, a quarter of '
      + "that run's entire re-read cost. The line numbers below are of THIS file; "
      + '`sed -n \'<from>,<to>p\' ' + f + '` costs a fraction of a whole read.', '',
    '```', ...body, '```', '', MARK_B, ''];
  const height = block.length;
  const fixed = block.map(l => l.replace(/§L(\d+)/g, (_, n) => `L${Number(n) + height}`));

  lines.splice(at, 0, ...fixed);
  fs.writeFileSync(f, lines.join('\n'));
  console.log(`${f}: ${heads.length} sections indexed at line ${at + 1}`);
}
